use maud::{html, Markup, PreEscaped};

fn svg(class: &str, inner: &str) -> Markup {
    html! {
        svg
            class=(class)
            xmlns="http://www.w3.org/2000/svg"
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="2"
            stroke-linecap="round"
            stroke-linejoin="round"
        {
            (PreEscaped(inner))
        }
    }
}

